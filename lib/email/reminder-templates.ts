/**
 * Generate plain text email for payment reminder
 */
export function generateReminderEmailText(data: ReminderEmailData): string {
  const {
    invoice,
    customer,
    reminderLevel,
    daysOverdue,
    actionUrl,
    interestAmount,
    interestRate,
    interestDays,
    reminderFee,
  } = data
  // Payment details follow the invoice currency, same as the invoice email
  // and PDF: a EUR reminder must never print the SEK account's IBAN.
  const company = companyWithInvoicePaymentAccount(data.company, invoice.currency)
  const config = REMINDER_CONFIG[reminderLevel]
  const interestRatePercent = (interestRate * 100).toLocaleString('sv-SE', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  })
  const hasInterest = interestAmount > 0
  const hasFee = reminderFee > 0
  const amounts = calculateReminderAmounts({
    invoiceTotal: reminderPrincipal(invoice, company),
    interestAmount,
    reminderFee,
    currency: invoice.currency,
  })

  let text = `${config.title.toUpperCase()}\n`
  text += `Faktura ${invoice.invoice_number} förföll för ${daysOverdue} dagar sedan\n`
  text += `=`.repeat(50) + `\n\n`

  text += `Hej${customer.name ? ` ${customer.name.split(' ')[0]}` : ''},\n\n`

  if (reminderLevel === 1) {
    text += `Vi vill påminna dig om att faktura ${invoice.invoice_number} förföll till betalning den ${formatDate(invoice.due_date)}.\n`
    text += `Om du redan har betalat kan du bortse från denna påminnelse.\n\n`
  } else if (reminderLevel === 2) {
    text += `Trots vår tidigare påminnelse har vi ännu inte mottagit betalning för faktura ${invoice.invoice_number} som förföll den ${formatDate(invoice.due_date)}.\n\n`
    text += `Vi ber dig vänligen att omgående reglera detta belopp för att undvika ytterligare åtgärder.\n\n`
  } else {
    text += `DETTA ÄR VÅR SLUTLIGA PÅMINNELSE\n\n`
    text += `Fakturan förföll till betalning den ${formatDate(invoice.due_date)} och vi har ännu inte mottagit betalning trots tidigare påminnelser.\n\n`
    text += `Om betalning inte inkommer inom 7 dagar kommer ärendet att överlämnas för vidare hantering.\n\n`
  }

  text += `Fakturasammanfattning:\n`
  text += `-`.repeat(30) + `\n`
  text += `Fakturanummer: ${invoice.invoice_number}\n`
  text += `Fakturadatum: ${formatDate(invoice.invoice_date)}\n`
  text += `Förfallodatum: ${formatDate(invoice.due_date)}\n`
  text += `Ursprungligt belopp: ${formatCurrency(reminderPrincipal(invoice, company), invoice.currency)}\n`
  if (hasInterest) {
    text += `Dröjsmålsränta (${interestRatePercent}% per år, ${interestDays} dagar): ${formatCurrency(interestAmount, invoice.currency)}\n`
  }
  if (hasFee) {
    text += `Påminnelseavgift: ${formatCurrency(reminderFee, REMINDER_FEE_CURRENCY)}\n`
  }
  text += `Att betala: ${formatReminderTotalDue(amounts)}\n`
  text += `-`.repeat(30) + `\n`
  if (amounts.feeDueSeparately > 0) {
    text += `${REMINDER_FEE_CURRENCY_NOTE}\n`
  }
  text += `\n`

  text += `Betalningsinformation:\n`
  if (company.bank_name) text += `Bank: ${company.bank_name}\n`
  if (company.clearing_number && company.account_number) {
    text += `Kontonummer: ${company.clearing_number}-${company.account_number}\n`
  }
  if (company.iban) text += `IBAN: ${company.iban}\n`
  if (company.bic) text += `BIC/SWIFT: ${company.bic}\n`
  text += `Meddelande: ${invoice.invoice_number}\n\n`

  text += `Har du redan betalat eller har frågor om fakturan?\n`
  text += `Hantera faktura: ${actionUrl}\n\n`

  text += `Har du frågor? Svara direkt på detta mejl så hjälper vi dig.\n\n`
  text += `Med vänliga hälsningar,\n`
  text += `${getCompanyDisplayName(company)}\n`

  if (company.org_number) {
    text += `\nOrg.nr: ${company.org_number}`
    if (company.vat_number) text += ` | VAT: ${company.vat_number}`
    text += `\n`
  }

  return text
}

/**
 * Generate email subject for payment reminder.
 *
 * When dröjsmålsränta or påminnelseavgift apply we surface them in the
 * subject so the customer sees the true amount to pay before opening
 * the email.
 */
export function generateReminderEmailSubject(data: ReminderEmailData): string {
  const { invoice, company, reminderLevel, interestAmount, reminderFee } = data
  const config = REMINDER_CONFIG[reminderLevel]
  const hasSurcharges = interestAmount > 0 || reminderFee > 0

  // A SEK fee on a foreign-currency invoice renders as "1 010,00 € + 60 kr":
  // two amounts in two currencies, never one mixed scalar.
  const amounts = calculateReminderAmounts({
    invoiceTotal: reminderPrincipal(invoice, company),
    interestAmount,
    reminderFee,
    currency: invoice.currency,
  })
  const suffix = hasSurcharges ? ' (inkl. dröjsmålsränta)' : ''

  return `${config.title}: Faktura ${invoice.invoice_number} - ${formatReminderTotalDue(amounts)}${suffix}`
}

/**
 * Get the number of days after due date for each reminder level
 */
export type ReminderDaysConfig = Record<1 | 2 | 3, number>

type ReminderDaysSettings = Partial<
  Pick<
    CompanySettings,
    'reminder_days_level_1' | 'reminder_days_level_2' | 'reminder_days_level_3'
  >
>

export function getReminderDaysConfig(
  settings?: ReminderDaysSettings | null,
): ReminderDaysConfig {
  const defaults: ReminderDaysConfig = {
    1: REMINDER_CONFIG[1].daysAfterDue,
    2: REMINDER_CONFIG[2].daysAfterDue,
    3: REMINDER_CONFIG[3].daysAfterDue,
  }

  const configured: ReminderDaysConfig = {
    1: settings?.reminder_days_level_1 ?? defaults[1],
    2: settings?.reminder_days_level_2 ?? defaults[2],
    3: settings?.reminder_days_level_3 ?? defaults[3],
  }

  const valid =
    Object.values(configured).every((days) => Number.isInteger(days) && days >= 1 && days <= 365)
    && configured[1] < configured[2]
    && configured[2] < configured[3]

  return valid ? configured : defaults
}
