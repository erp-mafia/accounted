/**
 * What the customer was asked to pay on the original invoice: the öre-rounded
 * "Att betala" minus any ROT/RUT-avdrag (fakturamodellen: the deduction is a
 * claim on Skatteverket, never on the customer). Reminders, dröjsmålsränta and
 * the amount-to-pay line must all start from this figure, not invoice.total,
 * or a privatperson is dunned for the SKV share and charged interest on it.
 */
export function reminderPrincipal(invoice: Invoice, company: CompanySettings): number {
  return getAmountToPay(invoice, company).toPay
}

export interface ReminderEmailData {
  invoice: Invoice
  customer: Customer
  company: CompanySettings
  reminderLevel: 1 | 2 | 3
  daysOverdue: number
  actionUrl: string // URL for customer to mark as paid or dispute
  // Dröjsmålsränta + lagstadgad påminnelseavgift (Räntelagen §6, Lag 1981:739).
  // When the reminder is generated by the cron, these are computed and persisted
  // on the invoice_reminders row and then passed in here.
  //
  // interestAmount is a share of the invoice total, so it carries the INVOICE
  // currency. reminderFee is a fixed statutory krona amount and always carries
  // SEK (see REMINDER_FEE_CURRENCY). The two are deliberately not summed here:
  // the amount to pay is derived per currency by calculateReminderAmounts().
  interestAmount: number
  interestRate: number    // annual rate as decimal (0.105 = 10.5%)
  interestFromDate: string
  interestDays: number
  reminderFee: number     // always SEK, never the invoice currency
}

/**
 * The lagstadgad påminnelseavgift is a Swedish-krona statute: Lag (1981:739) om
 * ersättning för inkassokostnader m.m. 2 §, with the amount fixed at 60 kr by
 * förordning (1981:1057) 1 §. There is no conversion rule for a foreign-currency
 * claim, and Accounted books the fee 1510/3990 in SEK regardless of the invoice
 * currency (lib/bookkeeping/reminder-fee-entries.ts).
 *
 * So the fee is always quoted in SEK. Rendering "60" with the invoice's currency
 * code would demand roughly ten times the statutory amount from a EUR customer
 * and would not match the receivable recorded in the books.
 */
export const REMINDER_FEE_CURRENCY = 'SEK'

export interface ReminderAmounts {
  /** Invoice currency (uppercased ISO code). Carries the invoice total + interest. */
  currency: string
  /** invoice.total + dröjsmålsränta, plus the fee only when the invoice is itself in SEK. */
  totalDue: number
  /**
   * The påminnelseavgift in SEK when the invoice is in another currency, so it
   * has to be demanded alongside rather than inside `totalDue`. 0 when the fee
   * is already folded into `totalDue`.
   */
  feeDueSeparately: number
}

/**
 * Split the amount to pay per currency. Never returns a single scalar that mixes
 * a foreign invoice currency with the SEK statutory fee.
 */
export function calculateReminderAmounts(input: {
  invoiceTotal: number
  interestAmount: number
  reminderFee: number
  currency?: string | null
}): ReminderAmounts {
  const currency = (input.currency || REMINDER_FEE_CURRENCY).toUpperCase()
  const feeSharesInvoiceCurrency = currency === REMINDER_FEE_CURRENCY
  const fee = input.reminderFee > 0 ? Math.round(input.reminderFee * 100) / 100 : 0

  const totalDue =
    Math.round(
      (input.invoiceTotal + input.interestAmount + (feeSharesInvoiceCurrency ? fee : 0)) * 100,
    ) / 100

  return {
    currency,
    totalDue,
    feeDueSeparately: feeSharesInvoiceCurrency ? 0 : fee,
  }
}

/**
 * Render the amount to pay. When the statutory fee is in a different currency
 * than the invoice it is appended as its own amount ("1 010,00 € + 60 kr")
 * instead of being folded into a misleading single figure.
 */
export function formatReminderTotalDue(amounts: ReminderAmounts): string {
  const base = formatCurrency(amounts.totalDue, amounts.currency)
  if (amounts.feeDueSeparately <= 0) {
    return base
  }
  return `${base} + ${formatCurrency(amounts.feeDueSeparately, REMINDER_FEE_CURRENCY)}`
}

