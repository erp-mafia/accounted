/**
 * A key in a tool's outputSchema `required` list does not leave it unnoticed.
 *
 * A client keeps the tools/list it fetched and validates every result against
 * that copy. A key that has been in a tool's `required` list is demanded by
 * every connection made while it was there, so a result without it is refused
 * in the client. 2026-11-19: profile_summary left gnubok_get_agent_briefing's
 * result and its `required` list, and connections holding the earlier
 * tools/list refused every briefing.
 *
 * output-required-keys-baseline.json records, per tool, every key that is or
 * has been in the top-level `required` list of its outputSchema (a tool with
 * no such key has no line). This test:
 *
 *   - fails when a recorded key is no longer in the tool's `required` list,
 *     unless RETIRED_REQUIRED_KEYS names it with a note saying the result
 *     still carries it;
 *   - fails when a recorded tool is no longer registered;
 *   - passes, with a hint to record them, when a tool or a `required` key is
 *     new. Recording only ever adds: a recorded key stays recorded.
 *
 * Record additions:
 *
 *   UPDATE_OUTPUT_REQUIRED_KEYS_BASELINE=1 npx vitest run --project unit src/extensions/general/mcp-server/__tests__/output-required-keys.test.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { tools, type McpTool } from '../server'

type RequiredByTool = Record<string, string[]>
type RetiredKeys = Record<string, Record<string, string>>
type Baseline = { _note: string; required: RequiredByTool }

const BASELINE_FILE = 'output-required-keys-baseline.json'
const BASELINE_PATH = join(__dirname, BASELINE_FILE)
const TEST_PATH = 'src/extensions/general/mcp-server/__tests__/output-required-keys.test.ts'
const UPDATE_COMMAND = `UPDATE_OUTPUT_REQUIRED_KEYS_BASELINE=1 npx vitest run --project unit ${TEST_PATH}`

/**
 * Keys that left a tool's `required` list while its result still carries
 * them, as tool: { key: what the result holds }. An entry is added in the
 * change that takes the key out of `required`; the key stays in the baseline.
 */
const RETIRED_REQUIRED_KEYS: RetiredKeys = {
  gnubok_ask_question: {
    asked_at: 'still returned: when the question was filed',
    evidence: 'still returned: the records as <kind>:<id>',
    options: 'still returned: the answer options, an empty list without any',
    question: 'still returned: the question text',
  },
  gnubok_get_agent_briefing: {
    profile_summary: 'still returned, always null',
  },
}

const unique = (keys: string[]): string[] => [...new Set(keys)].sort()

const has = (record: Record<string, unknown>, name: string): boolean =>
  Object.prototype.hasOwnProperty.call(record, name)

/** The keys listed for a tool; none for a tool without a line. */
const keysOf = (byTool: RequiredByTool, name: string): string[] => (has(byTool, name) ? byTool[name] : [])

/** The retired keys of a tool. */
const retiredOf = (retired: RetiredKeys, name: string): string[] =>
  has(retired, name) ? Object.keys(retired[name]) : []

/** The top-level `required` list of a tool's outputSchema, sorted. */
function requiredKeys(tool: McpTool): string[] {
  const required: unknown = tool.outputSchema?.required
  if (!Array.isArray(required)) return []
  return unique(required.filter((key: unknown): key is string => typeof key === 'string'))
}

/** Every registered tool's required keys, by tool name. */
function currentRequired(): RequiredByTool {
  const current: RequiredByTool = {}
  for (const tool of tools) current[tool.name] = requiredKeys(tool)
  return current
}

function readBaseline(): Baseline {
  return JSON.parse(readFileSync(BASELINE_PATH, 'utf8')) as Baseline
}

/** One tool per line, tools and keys sorted. */
function serializeBaseline(required: RequiredByTool): string {
  const note =
    `Generated by ${TEST_PATH}: every key that is or has been in a tool's outputSchema required list. ` +
    `Keys are only ever added. Record additions with: ${UPDATE_COMMAND}`
  const lines = Object.keys(required)
    .sort()
    .map((name) => `    ${JSON.stringify(name)}: ${JSON.stringify(required[name])}`)
  return `{\n  "_note": ${JSON.stringify(note)},\n  "required": {\n${lines.join(',\n')}\n  }\n}\n`
}

/**
 * What the registry no longer honours of the record, and what the record does
 * not hold yet. `lost` and `added` are "tool: key" pairs.
 */
function compare(
  recorded: RequiredByTool,
  current: RequiredByTool,
  retired: RetiredKeys,
): { lost: string[]; removedTools: string[]; added: string[] } {
  const lost: string[] = []
  const removedTools: string[] = []
  const added: string[] = []
  for (const [name, keys] of Object.entries(recorded)) {
    if (!has(current, name)) {
      removedTools.push(name)
      continue
    }
    const now = keysOf(current, name)
    const exempt = retiredOf(retired, name)
    for (const key of keys) {
      if (!now.includes(key) && !exempt.includes(key)) lost.push(`${name}: ${key}`)
    }
  }
  for (const [name, keys] of Object.entries(current)) {
    const known = keysOf(recorded, name)
    for (const key of keys) {
      if (!known.includes(key)) added.push(`${name}: ${key}`)
    }
  }
  return { lost: lost.sort(), removedTools: removedTools.sort(), added: added.sort() }
}

describe('outputSchema required keys', () => {
  it('keeps every recorded key in the required list of its tool, or on record as retired', () => {
    const current = currentRequired()

    if (process.env.UPDATE_OUTPUT_REQUIRED_KEYS_BASELINE === '1') {
      // Recorded keys stay; current and retired keys join them. A tool that
      // is no longer registered keeps its line until it is deleted by hand.
      const next: RequiredByTool = existsSync(BASELINE_PATH) ? { ...readBaseline().required } : {}
      for (const [name, keys] of Object.entries(current)) {
        const all = unique([...keysOf(next, name), ...keys, ...retiredOf(RETIRED_REQUIRED_KEYS, name)])
        if (all.length > 0) next[name] = all
      }
      writeFileSync(BASELINE_PATH, serializeBaseline(next))
      return
    }

    const { lost, added } = compare(readBaseline().required, current, RETIRED_REQUIRED_KEYS)

    if (added.length > 0) {
      console.warn(
        `[output required keys] required keys the baseline does not record yet; record them with:\n  ${UPDATE_COMMAND}\n  ${added.join('\n  ')}`,
      )
    }

    expect(
      lost,
      [
        'A key left the outputSchema `required` list of its tool (tool: key). A client validates every result against the',
        'tools/list it holds, so a connection made before this change still requires the key and refuses a result without it.',
        'Keep returning the key (null is fine) and add it to RETIRED_REQUIRED_KEYS in',
        `${TEST_PATH} with a note saying the result still carries it.`,
        `Never just delete it from ${BASELINE_FILE}.`,
      ].join('\n'),
    ).toEqual([])
  })

  it('keeps every recorded tool registered', () => {
    const { removedTools } = compare(readBaseline().required, currentRequired(), RETIRED_REQUIRED_KEYS)
    expect(
      removedTools,
      [
        `A tool recorded in ${BASELINE_FILE} is no longer registered.`,
        'When the tool was removed, delete its line from the baseline in the same change.',
      ].join('\n'),
    ).toEqual([])
  })

  it('every retired entry names a recorded key that is no longer required', () => {
    const recorded = readBaseline().required
    const current = currentRequired()
    const problems: string[] = []
    for (const [name, keys] of Object.entries(RETIRED_REQUIRED_KEYS)) {
      for (const [key, note] of Object.entries(keys)) {
        if (!has(current, name)) {
          problems.push(`${name}: not a registered tool, delete the entry`)
        } else if (keysOf(current, name).includes(key)) {
          problems.push(`${name}: ${key} is in the required list again, delete the entry`)
        }
        if (!keysOf(recorded, name).includes(key)) {
          problems.push(`${name}: ${key} is not in ${BASELINE_FILE}, put it back with: ${UPDATE_COMMAND}`)
        }
        if (note.trim() === '') problems.push(`${name}: ${key} has no note saying what the result still carries`)
      }
    }
    expect(problems).toEqual([])
  })

  it('tells a lost key, a retired key, a removed tool and an addition apart', () => {
    const recorded: RequiredByTool = { tool_a: ['kept', 'left', 'retired'], tool_gone: ['any'] }
    const current: RequiredByTool = { tool_a: ['kept', 'new'], tool_new: ['first'], tool_bare: [] }
    const retired: RetiredKeys = { tool_a: { retired: 'still returned' } }
    expect(compare(recorded, current, retired)).toEqual({
      lost: ['tool_a: left'],
      removedTools: ['tool_gone'],
      added: ['tool_a: new', 'tool_new: first'],
    })
    // Without the retired map the retired key is lost too.
    expect(compare(recorded, current, {}).lost).toEqual(['tool_a: left', 'tool_a: retired'])
  })
})
