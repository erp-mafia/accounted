/**
 * The app's only icon set: Heroicons (outline), animated by
 * @heroicons-animated/react. Import icons from here, never from the package:
 * the adapter in animated-icon.tsx is what makes `className` size them, plays
 * them on hover of the surrounding link or button and respects reduced
 * motion. A missing icon is added here, picked from heroicons-animated.com.
 *
 * Deep imports keep each page's bundle to the icons it renders; this module
 * stays a plain (non-client) module so server components can render icons.
 */

export type { IconHandle, IconProps }

/** Any icon from this module: the type for icon props and lookup tables. */
export type Icon = ((props: IconProps) => ReactElement) & { displayName?: string }

function icon(source: SourceIcon, name: string): Icon {
  const Glyph = (props: IconProps) => <AnimatedIcon source={source} {...props} />
  Glyph.displayName = name
  return Glyph
}

